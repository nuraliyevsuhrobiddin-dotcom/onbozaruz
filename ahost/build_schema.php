function q($s) { return '`' . str_replace('`', '``', $s) . '`'; }

function sqlType($type, $ascii)
{
    $parts = explode(':', $type);
    switch ($parts[0]) {
        case 'uuid': return 'CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci';
        case 'text': return 'MEDIUMTEXT';
        case 'vc': return 'VARCHAR(' . (int)$parts[1] . ')' . ($ascii ? ' CHARACTER SET ascii COLLATE ascii_bin' : '');
        case 'int': return 'INT';
        case 'bigint': return 'BIGINT';
        case 'num': return isset($parts[1]) ? 'DECIMAL(' . $parts[1] . ')' : 'DECIMAL(24,6)';
        case 'float': return 'DOUBLE';
        case 'bool': return 'TINYINT(1)';
        case 'ts': return 'DATETIME(6)';
        case 'date': return 'DATE';
        case 'json':
        case 'textarr': return 'LONGTEXT';
    }
    throw new Exception("Unknown type $type");
}

function sqlDefault($type, $default)
{
    $base = explode(':', $type)[0];
    if ($default === null) return '';
    if ($default === '@now') return ' DEFAULT CURRENT_TIMESTAMP(6)';
    if (is_string($default) && $default !== '' && $default[0] === '@') return '';
    // MEDIUMTEXT/LONGTEXT literal defaults are not portable; PHP fills them in.
    if (in_array($base, ['text', 'json', 'textarr'], true)) return '';
    if (is_bool($default)) return ' DEFAULT ' . ($default ? '1' : '0');
    if (is_int($default) || is_float($default)) return ' DEFAULT ' . $default;
    return " DEFAULT '" . str_replace("'", "''", $default) . "'";
}

