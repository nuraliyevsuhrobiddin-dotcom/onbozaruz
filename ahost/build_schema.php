    $ascii = isset($t['ascii']) ? $t['ascii'] : [];
    $lines = [];
    foreach ($t['cols'] as $col => $spec) {
        list($type, $nullable, $default) = $spec;
        $lines[] = '  ' . q($col) . ' ' . sqlType($type, in_array($col, $ascii, true)) . ($nullable ? ' NULL' : ' NOT NULL') . sqlDefault($type, $default);
    }
    $lines[] = '  PRIMARY KEY (' . implode(', ', array_map('q', $t['pk'])) . ')';
    foreach (isset($t['unique']) ? $t['unique'] : [] as $u) {
        $lines[] = '  UNIQUE KEY ' . q('uq_' . $name . '_' . implode('_', $u)) . ' (' . implode(', ', array_map('q', $u)) . ')';
    }
    foreach (isset($t['index']) ? $t['index'] : [] as $i) {
        $lines[] = '  KEY ' . q('ix_' . $name . '_' . implode('_', $i)) . ' (' . implode(', ', array_map('q', $i)) . ')';
    }
    $out[] = 'CREATE TABLE IF NOT EXISTS ' . q($name) . " (\n" . implode(",\n", $lines) . "\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci ROW_FORMAT=DYNAMIC;";
    $out[] = '';
    foreach (isset($t['fks']) ? $t['fks'] : [] as $fk) {
        $fks[] = 'ALTER TABLE ' . q($name) . ' ADD CONSTRAINT ' . q(substr('fk_' . $name . '_' . $fk[0], 0, 64)) .
            ' FOREIGN KEY (' . q($fk[0]) . ') REFERENCES ' . q($fk[1]) . ' (' . q($fk[2]) . ') ON DELETE ' . $fk[3] . ';';
    }
}
